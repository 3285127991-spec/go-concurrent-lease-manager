// Package lease provides a concurrency-safe in-memory lease manager.
package lease

import (
	"errors"
	"fmt"
	"sort"
	"sync"
	"time"
)

var (
	// ErrInvalidTTL is returned by NewManager when ttl is not positive.
	ErrInvalidTTL = errors.New("lease: ttl must be positive")
	// ErrEmptyKey is returned when a key is empty.
	ErrEmptyKey = errors.New("lease: key must not be empty")
	// ErrEmptyOwner is returned when an owner is empty.
	ErrEmptyOwner = errors.New("lease: owner must not be empty")
	// ErrLeaseHeld is returned by Acquire when the key already has an
	// active lease.
	ErrLeaseHeld = errors.New("lease: resource already has an active lease")
	// ErrLeaseNotFound is returned when the key has no active lease
	// (missing or expired).
	ErrLeaseNotFound = errors.New("lease: no active lease for key")
	// ErrOwnerMismatch is returned when the owner does not match the
	// active lease.
	ErrOwnerMismatch = errors.New("lease: owner does not match active lease")
	// ErrTokenMismatch is returned when the token does not match the
	// active lease.
	ErrTokenMismatch = errors.New("lease: token does not match active lease")
)

// Lease is a time-boxed grant on a resource key. Token is generated by
// the Manager and is never reused.
type Lease struct {
	Key       string
	Owner     string
	Token     string
	ExpiresAt time.Time
}

// Manager hands out leases for resource keys. Each key has at most one
// active lease at a time. All methods are safe for concurrent use.
type Manager struct {
	mu       sync.RWMutex
	ttl      time.Duration
	clock    Clock
	leases   map[string]*Lease
	tokenSeq uint64
}

// Option customizes a Manager.
type Option func(*Manager)

// WithClock sets the clock used for expiry decisions. A nil clock is
// ignored. Without this option the manager uses the system clock.
func WithClock(c Clock) Option {
	return func(m *Manager) {
		if c != nil {
			m.clock = c
		}
	}
}

// NewManager creates a Manager with the given positive ttl.
func NewManager(ttl time.Duration, opts ...Option) (*Manager, error) {
	if ttl <= 0 {
		return nil, ErrInvalidTTL
	}
	m := &Manager{
		ttl:    ttl,
		clock:  realClock{},
		leases: make(map[string]*Lease),
	}
	for _, opt := range opts {
		opt(m)
	}
	return m, nil
}

// TTL returns the lease duration configured at creation.
func (m *Manager) TTL() time.Duration { return m.ttl }

// Acquire takes a lease on key for owner. It fails with ErrLeaseHeld if
// the key already has an active lease. An expired lease is treated as
// absent and replaced by a new lease with a fresh token.
func (m *Manager) Acquire(key, owner string) (Lease, error) {
	if key == "" {
		return Lease{}, ErrEmptyKey
	}
	if owner == "" {
		return Lease{}, ErrEmptyOwner
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	now := m.clock.Now()
	if existing, ok := m.leases[key]; ok {
		if now.Before(existing.ExpiresAt) {
			return Lease{}, ErrLeaseHeld
		}
		delete(m.leases, key)
	}
	m.tokenSeq++
	l := &Lease{
		Key:       key,
		Owner:     owner,
		Token:     fmt.Sprintf("token-%d", m.tokenSeq),
		ExpiresAt: now.Add(m.ttl),
	}
	m.leases[key] = l
	return *l, nil
}

// Renew extends the active lease on key by one ttl. Owner and token must
// both match the active lease.
func (m *Manager) Renew(key, owner, token string) (Lease, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	l, err := m.activeLocked(key)
	if err != nil {
		return Lease{}, err
	}
	if err := authorize(l, owner, token); err != nil {
		return Lease{}, err
	}
	l.ExpiresAt = m.clock.Now().Add(m.ttl)
	return *l, nil
}

// Release drops the active lease on key. Owner and token must both match
// the active lease.
func (m *Manager) Release(key, owner, token string) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	l, err := m.activeLocked(key)
	if err != nil {
		return err
	}
	if err := authorize(l, owner, token); err != nil {
		return err
	}
	delete(m.leases, key)
	return nil
}

// Get returns the active lease for key, or false if there is none.
func (m *Manager) Get(key string) (Lease, bool) {
	m.mu.RLock()
	defer m.mu.RUnlock()
	l, ok := m.leases[key]
	if !ok || !m.clock.Now().Before(l.ExpiresAt) {
		return Lease{}, false
	}
	return *l, true
}

// Snapshot returns copies of all active leases ordered by key. The
// result is detached from internal state.
func (m *Manager) Snapshot() []Lease {
	m.mu.RLock()
	defer m.mu.RUnlock()
	now := m.clock.Now()
	out := make([]Lease, 0, len(m.leases))
	for _, l := range m.leases {
		if now.Before(l.ExpiresAt) {
			out = append(out, *l)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Key < out[j].Key })
	return out
}

// Len returns the number of active leases.
func (m *Manager) Len() int {
	m.mu.RLock()
	defer m.mu.RUnlock()
	now := m.clock.Now()
	n := 0
	for _, l := range m.leases {
		if now.Before(l.ExpiresAt) {
			n++
		}
	}
	return n
}

// activeLocked returns the active lease for key, treating an expired
// lease as absent and dropping it lazily. The caller must hold m.mu.
func (m *Manager) activeLocked(key string) (*Lease, error) {
	l, ok := m.leases[key]
	if !ok {
		return nil, ErrLeaseNotFound
	}
	if !m.clock.Now().Before(l.ExpiresAt) {
		delete(m.leases, key)
		return nil, ErrLeaseNotFound
	}
	return l, nil
}

func authorize(l *Lease, owner, token string) error {
	if l.Owner != owner {
		return ErrOwnerMismatch
	}
	if l.Token != token {
		return ErrTokenMismatch
	}
	return nil
}
